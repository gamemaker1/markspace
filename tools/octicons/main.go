// Command octicons copies the Octicons that Markspace uses out of an
// unpacked @primer/octicons npm package.
//
// It writes the 16 and 24 pixel SVG files and the licence into
// static/vendor/octicons-VERSION, the path data into static/js/octicons.js
// and the same path data into icons.go. Run it from internal/web
// through go generate.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

// icons lists every Octicon named in docs/primer.md sections 4.3 and 5, sorted.
var icons = []string{
	"ai-model", "alert", "alert-fill", "apps", "arrow-left", "arrow-right",
	"bold", "book", "check", "check-circle", "check-circle-fill",
	"chevron-down", "chevron-left", "chevron-right", "chevron-up", "clock",
	"cloud", "cloud-offline", "code", "comment", "copy", "dash",
	"device-desktop", "download", "duplicate", "eye", "file", "file-added",
	"file-directory-fill", "file-directory-open-fill", "file-moved", "file-zip",
	"filter", "gear", "globe", "grabber", "hash", "heading", "history", "home",
	"horizontal-rule", "image", "info", "issue-reopened", "italic", "kebab-horizontal", "key",
	"light-bulb", "link", "list-ordered", "list-unordered", "lock", "moon",
	"note", "paperclip", "pencil", "people", "person", "plus", "quote",
	"report", "screen-full", "screen-normal", "search", "share",
	"sidebar-collapse", "sidebar-expand", "sign-out", "sort-asc", "sort-desc",
	"sparkle", "star", "star-fill", "stop", "strikethrough", "sun", "sync",
	"table", "tag", "tasklist", "three-bars", "trash", "triangle-down",
	"typography", "undo", "unmute", "upload", "video", "x",
}

// heights lists the icon heights Markspace ships.
var heights = []int{16, 24}

// pathMarkup matches path data made only of plain path elements with a d
// attribute. The client helper parses exactly this form.
var pathMarkup = regexp.MustCompile(`^(<path d="[^"]*"></path>)+$`)

type iconData struct {
	Heights map[string]struct {
		Width int    `json:"width"`
		Path  string `json:"path"`
	} `json:"heights"`
}

func main() {
	src := flag.String("src", "", "directory of the unpacked @primer/octicons package")
	version := flag.String("version", "", "expected package version")
	flag.Parse()
	if *src == "" || *version == "" {
		fmt.Fprintln(os.Stderr, "octicons: -src and -version are required")
		os.Exit(2)
	}
	if err := run(*src, *version); err != nil {
		fmt.Fprintln(os.Stderr, "octicons:", err)
		os.Exit(1)
	}
}

func run(src, version string) error {
	var pkg struct {
		Name    string `json:"name"`
		Version string `json:"version"`
	}
	if err := readJSON(filepath.Join(src, "package.json"), &pkg); err != nil {
		return err
	}
	if pkg.Name != "@primer/octicons" || pkg.Version != version {
		return fmt.Errorf("package is %s %s, want @primer/octicons %s", pkg.Name, pkg.Version, version)
	}
	var data map[string]iconData
	if err := readJSON(filepath.Join(src, "build", "data.json"), &data); err != nil {
		return err
	}

	vendor := filepath.Join("static", "vendor", "octicons-"+version)
	if err := os.RemoveAll(vendor); err != nil {
		return err
	}
	if err := os.MkdirAll(vendor, 0o755); err != nil {
		return err
	}
	if err := copyFile(filepath.Join(src, "LICENSE"), filepath.Join(vendor, "LICENSE")); err != nil {
		return err
	}

	var keys, paths []string
	for _, name := range icons {
		icon, ok := data[name]
		if !ok {
			return fmt.Errorf("icon %q is not in data.json", name)
		}
		for _, h := range heights {
			entry, ok := icon.Heights[strconv.Itoa(h)]
			if !ok {
				return fmt.Errorf("icon %q has no height %d", name, h)
			}
			if entry.Width != h {
				return fmt.Errorf("icon %q at height %d has width %d", name, h, entry.Width)
			}
			if !pathMarkup.MatchString(entry.Path) {
				return fmt.Errorf("icon %q at height %d has markup other than path elements", name, h)
			}
			file := fmt.Sprintf("%s-%d.svg", name, h)
			if err := copyFile(filepath.Join(src, "build", "svg", file), filepath.Join(vendor, file)); err != nil {
				return err
			}
			keys = append(keys, fmt.Sprintf("%s-%d", name, h))
			paths = append(paths, entry.Path)
		}
	}

	if err := os.WriteFile(filepath.Join("static", "js", "octicons.js"), jsFile(version, keys, paths), 0o644); err != nil {
		return err
	}
	goSrc, err := goFile(version, keys, paths)
	if err != nil {
		return err
	}
	return os.WriteFile("icons.go", goSrc, 0o644)
}

func jsFile(version string, keys, paths []string) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by octicons from @primer/octicons %s. DO NOT EDIT.\n", version)
	fmt.Fprintf(&b, "// Octicons are MIT licensed, copyright GitHub Inc. The licence is in\n")
	fmt.Fprintf(&b, "// static/vendor/octicons-%s/LICENSE.\n\n", version)
	fmt.Fprintf(&b, "/** Release of @primer/octicons the path data comes from. */\n")
	fmt.Fprintf(&b, "export const VERSION = %q;\n\n", version)
	fmt.Fprintf(&b, "/** Path markup from build/data.json, keyed by icon name and height. */\n")
	b.WriteString("export const PATHS = {\n")
	entries := make([]string, len(keys))
	for i := range keys {
		entries[i] = "  " + jsonString(keys[i]) + ": " + jsonString(paths[i])
	}
	b.WriteString(strings.Join(entries, ",\n"))
	b.WriteString("\n};\n")
	return b.Bytes()
}

func goFile(version string, keys, paths []string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by octicons from @primer/octicons %s. DO NOT EDIT.\n\n", version)
	b.WriteString("package web\n\n")
	b.WriteString("// octiconVersion is the @primer/octicons release the path data comes from.\n")
	fmt.Fprintf(&b, "const octiconVersion = %q\n\n", version)
	b.WriteString("// octiconPaths holds path markup from build/data.json, keyed by icon name\n// and height.\n")
	b.WriteString("var octiconPaths = map[string]string{\n")
	for i := range keys {
		fmt.Fprintf(&b, "%q: %q,\n", keys[i], paths[i])
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// jsonString encodes s as a JSON string and leaves HTML characters as they
// are, so the markup stays readable in octicons.js.
func jsonString(s string) string {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s)
	return strings.TrimSuffix(b.String(), "\n")
}

func readJSON(name string, v any) error {
	raw, err := os.ReadFile(name)
	if err != nil {
		return err
	}
	if err := json.Unmarshal(raw, v); err != nil {
		return fmt.Errorf("%s: %w", name, err)
	}
	return nil
}

func copyFile(from, to string) error {
	raw, err := os.ReadFile(from)
	if err != nil {
		return err
	}
	return os.WriteFile(to, raw, 0o644)
}
